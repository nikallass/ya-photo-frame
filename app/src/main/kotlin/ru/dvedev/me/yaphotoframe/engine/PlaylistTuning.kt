package ru.dvedev.me.yaphotoframe.engine

/**
 * Чем задаётся порядок показа.
 *
 * Числа подобраны под семейный архив: несколько сотен снимков, которые
 * пополняются вручную и понемногу.
 */
data class PlaylistTuning(
    /**
     * Какая доля недавно показанного вовсе не участвует в выборе.
     *
     * Без этого при полусотне снимков один и тот же лез бы по два-три раза за
     * вечер, и рамка казалась бы зациклённой. Если запрет не оставляет никого,
     * он снимается — лучше повтор, чем чёрный экран.
     */
    val hardCooldownFraction: Float = 0.5f,

    /**
     * Наименьший вес того, что показывали совсем недавно, относительно самого
     * давнего. Ноль означал бы вечный запрет, единица — что остывания нет.
     */
    val softCooldownFloor: Float = 0.15f,

    /** Во сколько раз охотнее показывается только что добавленное. */
    val freshnessStrength: Float = 3f,

    /** Сколько длится «недавно добавлено», после чего бонус сходит на нет. */
    val freshnessWindowMillis: Long = 14L * 24 * 60 * 60 * 1000,
)
