package ru.dvedev.me.yaphotoframe.media

/**
 * Откуда рамка берёт содержимое.
 *
 * Интерфейс существует не ради абстракции как таковой: в спеке зафиксировано, что
 * первая версия работает с публичной ссылкой, а авторизованный доступ добавляется
 * позже, и добавление не должно потребовать переписывания всего остального.
 */
interface MediaSource {

    /**
     * Содержимое библиотеки.
     *
     * В первой версии — плоский список корня папки. Рекурсивный обход подпапок
     * появится отдельным шагом и заменит реализацию, не трогая вызывающий код.
     */
    suspend fun list(): List<MediaItem>

    /**
     * Ссылка на сам файл — не на уменьшенную копию.
     *
     * Нужна видео: маленькое скачивается в кэш целиком, большое проигрывается
     * потоком по этой же ссылке. Ссылка живёт недолго, поэтому запрашивается
     * непосредственно перед использованием, а не хранится в индексе.
     */
    suspend fun downloadUrl(item: MediaItem): String

    /**
     * Первый попавшийся элемент, который есть чем показать.
     *
     * Нужен для холодного старта: полный обход большой папки — это десятки
     * запросов и полминуты, и всё это время владелец смотрел бы в чёрный экран.
     * Обход останавливается на первой же подходящей находке.
     */
    suspend fun firstShowable(): MediaItem?

    /**
     * Подпапки указанной папки — для выбора того, что показывать.
     *
     * Дерево раскрывается по одному уровню за раз: обходить его целиком ради
     * списка папок значило бы ждать десятки секунд при каждом открытии
     * страницы.
     */
    suspend fun subfolders(path: String): List<Folder>

    /**
     * Все папки хранилища целиком, без оглядки на отбор.
     *
     * Обход неспешный: между обращениями выдерживается пауза. Быстро гнать
     * сотни запросов подряд ради списка, который нужен раз в неделю, незачем —
     * и хранилищу спокойнее.
     */
    suspend fun allFolders(): List<Folder>
}

/** Папка внутри расшаренной директории. */
data class Folder(val name: String, val path: String)
